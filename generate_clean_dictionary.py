def extract_sources(definition):
    sources = []
    known_keywords = [
        'المجمع', 'مجمع', 'المصباح', 'مصباح', 'اللسان', 'لسان', 'التحرير', 'تحرير',
        'اللمعة', 'لمعة', 'المسالك', 'مسالك', 'الجواهر', 'جواهر', 'الشرايع', 'الشرائع',
        'العروة', 'عروة', 'المكاسب', 'مكاسب', 'المفردات', 'مفردات', 'أقرب الموارد',
        'المنجد', 'منجد', 'قاموس', 'فرهنگ', 'الوسائل', 'وسائل', 'الينابيع', 'ينابيع',
        'البحار', 'بحار', 'التعريفات', 'تعريفات', 'التبصرة', 'تبصرة', 'مفتاح',
        'الأخلاق', 'الفتاوى الواضحة', 'الواضحة', 'تفسير', 'الميزان', 'التبيان',
        'كشف اللثام', 'دروس في علم الأصول', 'أصول', 'جامع السعادات', 'سفينة البحار',
        'الحدود والحقائق', 'الدراية', 'الوجيز', 'الوجيزة', 'نهج البلاغة', 'الخصال',
        'الذكرى', 'المنطق', 'منهاج', 'المستمسك', 'مكتب', 'عن بعض', 'ابن سيدة', 'الأزهري',
        'صاحب القاموس', 'ابن الأثير'
    ]
    matches = re.findall(r'[\(\[\{«]([^\)\]\}»]{3,120})[\)\]\}»]', definition)
    for m in matches:
        m_clean = m.strip(' .،:-')
        for kw in known_keywords:
            if kw in m_clean:
                if m_clean not in sources:
                    sources.append(m_clean)
                break
    return sources

